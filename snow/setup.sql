-- What TfL reported, every 2 minutes: an audit trail and a disruption history.
CREATE TABLE IF NOT EXISTS LINE_STATUS (
  CAPTURED_AT TIMESTAMP_TZ, LINE_ID STRING, LINE_NAME STRING, MODE STRING,
  SEVERITY NUMBER, STATUS STRING, REASON STRING);

-- Control Room scenarios and the briefing Cortex wrote for each.
CREATE TABLE IF NOT EXISTS SCENARIOS (
  CREATED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(), TITLE STRING, PAYLOAD VARIANT,
  BRIEFING STRING, MODEL STRING);

-- Game Mode results, for the all-time leaderboard.
CREATE TABLE IF NOT EXISTS GAME_RESULTS (
  PLAYED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(), ROOM STRING, PLAYER STRING, ROUND_NO NUMBER,
  ORIGIN STRING, DESTINATION STRING, BASE_MINUTES FLOAT, NEW_MINUTES FLOAT, POINTS FLOAT, DETAIL VARIANT);

-- The app role can read and write every table here, now and in future.
